import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import {
  DeterministicGateRunner,
  type GateResult,
  type GateRung,
  loadGatesConfig,
} from "@sekhemet/gates";
import { ProcessSandbox } from "@sekhemet/sandbox";

/**
 * The synthetic git fixture generator (X21, design "Deterministic testing
 * and mock infrastructure"): miniature repositories in TypeScript, Python
 * and Rust, each with a source file, a failing-or-passing test and a
 * `.sekhemet/gates.toml`. `generateFixture` writes one (`sekhemet fixture`,
 * and the committed copies under fixtures/mini/). `createTestWorktree`
 * copies a pre-initialised git template into a temporary directory, so a
 * test gets a fresh repository in milliseconds, runs the gates, and cleans up.
 */
export type FixtureLanguage = "typescript" | "python" | "rust";
export const FIXTURE_LANGUAGES: readonly FixtureLanguage[] = ["typescript", "python", "rust"];

export interface FixtureOptions {
  /** Plant a bug the fixture's test catches (for repair-loop tests). */
  bug?: boolean;
}

const TOML_HEAD = `# Generated by the Sekhemet fixture generator (X21).
[project]
protected = ["tests/**", ".sekhemet/gates.toml"]
max_files = 3
max_diff_lines = 200
`;

/** Parse every module without writing bytecode (the sandbox forbids the cache). */
const PY_PARSE =
  "import ast, pathlib; [ast.parse(p.read_text(), str(p)) for p in pathlib.Path('.').rglob('*.py')]";

function gate(id: string, rung: GateRung, command: string, args: string[], timeout = 120): string {
  return `
[[gate]]
id = "${id}"
rung = "${rung}"
layer = "${rung === "test" ? "functional" : "static"}"
command = "${command}"
args = [${args.map((a) => JSON.stringify(a)).join(", ")}]
timeout_s = ${timeout}
parser = "generic"
`;
}

/** The files of one fixture, by path. */
export function fixtureFiles(
  lang: FixtureLanguage,
  opts: FixtureOptions = {},
): Record<string, string> {
  const op = opts.bug ? "-" : "+";
  switch (lang) {
    case "typescript":
      return {
        "package.json": `${JSON.stringify({ name: "mini-ts", private: true, type: "module", scripts: { test: "node --test tests/*.test.ts" } }, null, 2)}\n`,
        "src/add.ts": `export function add(a: number, b: number): number {\n  return a ${op} b;\n}\n`,
        "tests/add.test.ts": `import assert from "node:assert/strict";\nimport { test } from "node:test";\nimport { add } from "../src/add.ts";\n\ntest("add", () => {\n  assert.equal(add(2, 3), 5);\n});\n`,
        ".sekhemet/gates.toml": `${TOML_HEAD}${gate("unit", "test", "node", ["--test", "tests/*.test.ts"])}`,
      };
    case "python":
      return {
        "pyproject.toml": `[project]\nname = "mini-py"\nversion = "0.1.0"\n`,
        "mini/__init__.py": "",
        "mini/add.py": `def add(a: int, b: int) -> int:\n    return a ${op} b\n`,
        "tests/__init__.py": "",
        "tests/test_add.py": `import unittest\n\nfrom mini.add import add\n\n\nclass AddTest(unittest.TestCase):\n    def test_add(self) -> None:\n        self.assertEqual(add(2, 3), 5)\n\n\nif __name__ == "__main__":\n    unittest.main()\n`,
        ".sekhemet/gates.toml": `${TOML_HEAD}${gate("parse", "parse", "python3", ["-B", "-c", PY_PARSE])}${gate("unit", "test", "python3", ["-B", "-m", "unittest", "discover", "-s", "tests", "-t", "."])}`,
      };
    case "rust":
      return {
        "Cargo.toml": `[package]\nname = "mini_rs"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n`,
        "src/lib.rs": `pub fn add(a: i64, b: i64) -> i64 {\n    a ${op} b\n}\n`,
        "tests/add.rs":
          "use mini_rs::add;\n\n#[test]\nfn adds() {\n    assert_eq!(add(2, 3), 5);\n}\n",
        ".gitignore": "target/\n",
        ".sekhemet/gates.toml": `${TOML_HEAD}${gate("unit", "test", "cargo", ["test", "--quiet", "--offline"], 300)}`,
      };
  }
}

/** Write a fixture repository into `dir` (not a git repository yet). */
export function generateFixture(
  lang: FixtureLanguage,
  dir: string,
  opts: FixtureOptions = {},
): string[] {
  const files = fixtureFiles(lang, opts);
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  }
  return Object.keys(files).sort();
}

const git = (cwd: string, ...args: string[]) =>
  execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();

/** Initialised templates, one per language and variant, built once per process. */
const templates = new Map<string, string>();

function template(lang: FixtureLanguage, opts: FixtureOptions): string {
  const key = `${lang}:${opts.bug ? "bug" : "ok"}`;
  const cached = templates.get(key);
  if (cached && existsSync(cached)) return cached;
  const dir = mkdtempSync(join(tmpdir(), `sek-fixture-${lang}-`));
  generateFixture(lang, dir, opts);
  git(dir, "init", "-q", "-b", "main");
  git(dir, "config", "user.email", "fixture@sekhemet.local");
  git(dir, "config", "user.name", "Sekhemet Fixture");
  git(dir, "add", "-A");
  git(
    dir,
    "commit",
    "-q",
    "-m",
    `chore: ${lang} fixture\n\nCard: fixture\nAgent-Model: none\nAgent-Harness: sekhemet\nAgent-Role: implementer\nCo-authored-by: Sekhemet Fixture <fixture@sekhemet.local>`,
  );
  templates.set(key, dir);
  process.once("exit", () => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

export interface TestWorktree {
  path: string;
  lang: FixtureLanguage;
  git: (...args: string[]) => string;
  /** The fixture's own gates.toml, run with the real gate runner. */
  runGates: (rungs?: GateRung[]) => Promise<GateResult>;
  cleanup: () => void;
}

/**
 * A fresh fixture repository in a temporary directory: a copy of the
 * pre-initialised template (git history included), not a new `git init`.
 */
export function createTestWorktree(lang: FixtureLanguage, opts: FixtureOptions = {}): TestWorktree {
  const from = template(lang, opts);
  const path = mkdtempSync(join(tmpdir(), `sek-wt-${lang}-`));
  cpSync(from, path, { recursive: true });
  return {
    path,
    lang,
    git: (...args) => git(path, ...args),
    runGates: async (rungs) => {
      const config = loadGatesConfig(path);
      const runner = new DeterministicGateRunner(new ProcessSandbox(), {
        repoRoot: path,
        expectedConfigSha256: config.sha256,
      });
      return runner.runGates(rungs ?? [...new Set(config.gates.map((g) => g.rung))], path);
    },
    cleanup: () => rmSync(path, { recursive: true, force: true }),
  };
}
